// Package examples 是每个框架模块一个最小可运行示例的集合。
//
// ## 这个目录解决什么问题
//
// 别人拿到 pkg/cachex 要自己读 200 行源码、拼出正确的初始化顺序、
// 猜哪些参数不配会静默降级 —— 示例是开源框架降低上手成本最有效的一件工具。
//
// 本目录的约定:
//
//	examples/<包名>/main.go   —— 一包一个目录,package main,可 `go run ./examples/<包名>`
//
// ⚠️ **示例必须是能跑的代码**,不是伪代码。GitBook 文档(#3)里引用的片段
// 全部来自这里 —— 文档写的示例如果跑不起来,比没有文档更糟。
//
// ## 约束
//
//   - 只依赖公开 API,不 import internal/service 等业务包
//   - 需要外部基础设施的(Redis / DB / OSS),示例里演示**装配代码**,
//     但运行时不真连 —— 没配就打印提示并跳过,不让 `go run` 直接 panic
//   - 示例之间互不依赖,可以单独跑
//
// ## 漂移网
//
// examples_test.go 里有一条测试:internal/pkg 下每个顶层包目录
// 都必须有一个同名 examples 子目录。新增框架模块却忘了写示例 ⇒ 测试红。
