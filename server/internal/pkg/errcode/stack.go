// 错误堆栈链(借鉴 GoFrame gerror 的机制,在 errcode 包内实现)。
//
// # 解决什么
//
// service 层大量 `fmt.Errorf("...: %w", err)` 包装,错误一路传到
// BaseHandler.Fail / 日志时只剩一条 message 串 —— **错误在哪一行产生、
// 被谁包装过,日志里没有**。本文件把"包装点调用栈"钉在错误对象上:
// New/Newf/Wrap/Wrapf 在调用瞬间拍栈,Stack() 把整条包装链的栈合并
// 去重后输出成可读文本。
//
// # 为什么放 errcode 包内,而不是新开 errstack 包
//
// 栈是错误对象自带的证据,和 Code/Message/Detail 同属一个对象的状态;
// 新开包则 errcode 要反过来 import 它(或者调用方两个包都要碰),
// 模块边界没有变干净,反而多一个包。errcode 本来就是"业务错误"的家。
//
// # 为什么不直接拷 gerror 源码
//
// gerror 依赖 internal/errors、gconv 等框架内部件,拆出来就是拔线团;
// 这里只借它的机制:创建时拍栈(不是打印时)、跨层去重、过滤框架帧。
//
// # 硬约束
//
// Unwrap 必须透传 —— 全仓取业务码靠 errors.As(CodeOf),M112 的教训:
// 任何让 errors.As/Is 失灵的包装都是回归。Stack 只进日志,不进 wire
// (Fail 仍然只发 Message,前端零感知)。
package errcode

import (
	"errors"
	"fmt"
	"runtime"
	"strconv"
	"strings"
)

// Stack 调用栈快照(PC 列表)。
type Stack []uintptr

// stackDepth 单次捕获的最大帧数。32 帧对排障足够;更深的链一般是
// runtime 自身,本来就会被过滤掉。
const stackDepth = 32

// stackFilterKeys 直接从栈里剔除的路径片段(框架自身机器帧,不属于证据)。
//
// ⚠️ 按文件过滤而不是按包过滤:本包内还有合法的"业务帧"场景(测试就在
// errcode 包里),按包过滤会把它们一起杀掉。
var stackFilterKeys = []string{
	"internal/pkg/errcode/stack.go", // capture / Wrap / Wrapf
	"internal/pkg/errcode/error.go", // New / Newf
	"<autogenerated>",               // 编译器生成的桥接帧
}

// capture 捕获调用栈。
//
// # 为什么 skip=1 而不是"跳三层直接落到业务调用点"
//
// 固定 skip 数在**内联**下不可靠:capture 太小会被内联进 New/Wrap,甚至
// New 再被内联进调用方,物理帧数随内联漂移,skip=3 实测会落到 testing
// 的帧上(tRunner),业务调用点整个丢失。所以只跳一层(runtime.Callers
// 自身),拿到原始 PC 列表后**按路径丢弃 errcode 包自己的帧** ——
// 无论内联怎么组合,第一个留下的帧总是真正的调用点。
func capture() Stack {
	pcs := make([]uintptr, stackDepth)
	n := runtime.Callers(1, pcs)
	if n == 0 {
		return nil
	}
	out := pcs[:0]
	for _, pc := range pcs[:n] {
		fn := runtime.FuncForPC(pc - 1)
		if fn != nil {
			file, _ := fn.FileLine(pc - 1)
			if !renderFrame(file) {
				continue
			}
		}
		out = append(out, pc)
	}
	return out
}

// stackCarrier 带栈的错误都实现它(不导出,StackOf 走链提取用)。
type stackCarrier interface {
	error
	stackFrames() Stack
	stackMessage() string // 本层自己的消息(不含被包装部分)
}

// ── errcode.Error 挂栈 ────────────────────────────────────────────

// Stack 返回这个错误的堆栈链文本(含包装链各层的栈,已去重)。
func (e *Error) Stack() string { return formatStackChain(e) }

func (e *Error) stackFrames() Stack { return e.st }

func (e *Error) stackMessage() string { return e.Message }

// ── 包装层 ────────────────────────────────────────────────────────

// wrapError 带栈的包装层:自己的消息 + 创建点栈 + 被包装错误。
type wrapError struct {
	msg string
	err error
	st  Stack
}

func (e *wrapError) Error() string {
	if e.err == nil {
		return e.msg
	}
	return e.msg + ": " + e.err.Error()
}

// Unwrap 透传 —— errors.As / errors.Is / CodeOf 必须能穿透本包装。
func (e *wrapError) Unwrap() error { return e.err }

func (e *wrapError) stackFrames() Stack { return e.st }

func (e *wrapError) stackMessage() string { return e.msg }

// Wrap 给错误包一层带调用栈的包装(借鉴 gerror.Wrap)。
//
// 与 `fmt.Errorf("...: %w", err)` 的差别就是多一份"哪一行包的"证据;
// errcode.Error 在包装层下面时,CodeOf 照常取得到业务码。
// err 为 nil 时返回 nil,可直接接在可能失败的调用后面。
func Wrap(err error, msg string) error {
	if err == nil {
		return nil
	}
	return &wrapError{msg: msg, err: err, st: capture()}
}

// Wrapf 带格式化的 Wrap。
func Wrapf(err error, format string, args ...interface{}) error {
	if err == nil {
		return nil
	}
	return &wrapError{msg: fmt.Sprintf(format, args...), err: err, st: capture()}
}

// StackOf 从错误链里提取堆栈链文本;链上没有任何带栈错误时返回 ""
// (纯 fmt.Errorf 链没有栈可给,不给就是诚实)。
func StackOf(err error) string {
	if err == nil {
		return ""
	}
	for e := err; e != nil; e = errors.Unwrap(e) {
		if _, ok := e.(stackCarrier); ok {
			return formatStackChain(err)
		}
	}
	return ""
}

// ── 渲染 ──────────────────────────────────────────────────────────

// formatStackChain 把错误链渲染成编号层 + 缩进帧的文本,形状对齐
// gerror.Stack():
//
//	1. 解析第 2 关审批人失败
//	   1). rapid-admin/internal/service/approval.(*Engine).resolve
//	        D:/…/approval_engine.go:120
//	2. [20601] 审批流程配置有误
//	   1). rapid-admin/internal/service/approval.(*Engine).submit
//	        D:/…/approval_engine.go:98
func formatStackChain(err error) string {
	type layer struct {
		msg    string
		frames Stack
	}

	// 1. 走链收集:每层一条消息,带栈的层附帧列表。
	var layers []layer
	for e := err; e != nil; e = errors.Unwrap(e) {
		l := layer{msg: ownMessage(e)}
		if c, ok := e.(stackCarrier); ok {
			l.msg = c.stackMessage()
			l.frames = c.stackFrames()
		}
		layers = append(layers, l)
	}
	if len(layers) == 0 {
		return ""
	}

	// 2. 跨层去重(对齐 gerror 的 filterLinesOfStackInfos):从最深层往上
	//    走,同一 file:line 在深层出现过就不再出现在上层 —— 包装链的栈
	//    大部分是同一条调用路径,不去重输出全是重复帧。
	seen := make(map[string]struct{})
	for i := len(layers) - 1; i >= 0; i-- {
		frames := layers[i].frames
		if len(frames) == 0 {
			continue
		}
		kept := make(Stack, 0, len(frames))
		for _, pc := range frames {
			fn := runtime.FuncForPC(pc - 1)
			if fn == nil {
				continue
			}
			file, line := fn.FileLine(pc - 1)
			if !renderFrame(file) {
				continue
			}
			key := file + ":" + strconv.Itoa(line)
			if _, dup := seen[key]; dup {
				continue
			}
			seen[key] = struct{}{}
			kept = append(kept, pc)
		}
		layers[i].frames = kept
	}

	// 3. 渲染。
	var b strings.Builder
	for i, l := range layers {
		fmt.Fprintf(&b, "%d. %s\n", i+1, l.msg)
		for j, pc := range l.frames {
			fn := runtime.FuncForPC(pc - 1)
			if fn == nil {
				continue
			}
			file, line := fn.FileLine(pc - 1)
			fmt.Fprintf(&b, "   %d). %s\n        %s:%d\n", j+1, fn.Name(), file, line)
		}
	}
	return b.String()
}

// ownMessage 取本层自己的消息:fmt.Errorf 包装层的 Error() 是
// "outer: inner",不剥掉后缀的话深层消息会重复出现。
func ownMessage(e error) string {
	inner := errors.Unwrap(e)
	if inner == nil {
		return e.Error()
	}
	return strings.TrimSuffix(e.Error(), ": "+inner.Error())
}

// renderFrame 文件路径要不要进输出:过滤 GOROOT(标准库 / testing 的帧)
// 与 stackFilterKeys 里列的框架自身路径。
func renderFrame(file string) bool {
	for _, k := range stackFilterKeys {
		if strings.Contains(file, k) {
			return false
		}
	}
	// ⚠️ FileLine 在 Windows 上给的是正斜杠路径("D:/Go/src/..."),
	// GOROOT() 是反斜杠("D:\Go"),直接 HasPrefix 永远失配 —— 统一成正斜杠再比。
	if goRoot := runtime.GOROOT(); goRoot != "" {
		goRoot = strings.ReplaceAll(goRoot, "\\", "/")
		if strings.HasPrefix(file, goRoot) {
			return false
		}
	}
	return true
}
