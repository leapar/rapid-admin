		//     其中 cookie 一级当前不可达 —— 全仓没有 SetCookie,详见 sseauth.go)
		//   - 不走 rbac 闭包:长连接不该占着鉴权链;权限在 handler 里用
		//     middleware.CanAccess 逐 topic 判定(见 event.go subscribableTopics)
		//   - 也不走 CSRF:SSE 只 GET,CSRF 不适用
		//   - 挂豁免清单见 consistency.go rbacExemptRoutes
