// gen-swagger-schema —— 生成「路由 handler → 请求体 DTO」注册表 + 字段说明表
//
// 输入(相对 server/ 模块根):
//
//	internal/api/handler/v1/*.go   —— 路由 handler 与它绑定的请求体 DTO
//	internal/service/*.go          —— DTO 结构体定义与字段注释
//	internal/model/*.go            —— 同上
//
// 输出:
//
//	internal/api/handler/v1/swagger_dto_gen.go
//
// 跑法(在 server/ 目录下):
//
//	go run ./cmd/gen-swagger-schema
//
// ⚠️ **改 handler / DTO 之后必须重跑**,否则 OpenAPI 里的字段契约会过期。
// 漂移由 cmd/gen-swagger-schema/main_test.go 盯着:它重跑一遍生成器,
// 跟仓库里那份逐字比 —— 不一致就红。
//
// 为什么用「生成」而不是「手写注册表」:
//
// 手写一份 "路由 → DTO" 的表,就是**第二份真相**。handler 里把
// `service.CreateUserRequest` 换成别的类型,那张表不会跟着变 ——
// 而且不会报错,只会让 Swagger UI 里的字段悄悄对不上实际接口。
// 这里让源码自己当真相,生成物只做搬运。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"os"
	"path/filepath"
	"sort"
)

const (
	// handlerDir handler 包目录(生成物也落在这里)
	handlerDir = "internal/api/handler/v1"
	// serviceDir service 包目录
	serviceDir = "internal/service"
	// modelDir model 包目录
	modelDir = "internal/model"
	// outName 生成文件名(相对 handlerDir)
	outName = "swagger_dto_gen.go"
	// handlerAlias handler 包的组件名前缀
	handlerAlias = "v1"
	// serviceAlias service 包的组件名前缀
	serviceAlias = "service"
	// modelAlias model 包的组件名前缀
	modelAlias = "model"
)

// result 一次分析的结果
type result struct {
	// dtos handler 方法 → DTO
	dtos map[string]*dtoRef
	// docs 组件名 → (json 字段名 → 说明)
	docs map[string]map[string]string
	// skipped 跳过的 handler 与原因(原样写进生成文件,别让"缺字段契约"变成静默事实)
	skipped []string
}

func main() {
	root, err := findModuleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "定位模块根失败:", err)
		os.Exit(1)
	}
	res, err := analyze(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "分析失败:", err)
		os.Exit(1)
	}
	content, err := render(res)
	if err != nil {
		fmt.Fprintln(os.Stderr, "生成失败:", err)
		os.Exit(1)
	}
	out := filepath.Join(root, handlerDir, outName)
	if err := os.WriteFile(out, content, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "写文件失败:", err)
		os.Exit(1)
	}
	fmt.Printf("已生成 %s(%d 个 handler → DTO, %d 个类型带字段说明)\n",
		out, len(res.dtos), len(res.docs))
	for _, s := range res.skipped {
		fmt.Fprintln(os.Stderr, "跳过:", s)
	}
}

// analyze 跑一遍完整分析
func analyze(root string) (*result, error) {
	hp, err := loadPkg(filepath.Join(root, handlerDir), handlerAlias)
	if err != nil {
		return nil, err
	}
	sp, err := loadPkg(filepath.Join(root, serviceDir), serviceAlias)
	if err != nil {
		return nil, err
	}
	mp, err := loadPkg(filepath.Join(root, modelDir), modelAlias)
	if err != nil {
		return nil, err
	}
	pkgs := map[string]*pkgInfo{
		handlerAlias: hp,
		serviceAlias: sp,
		modelAlias:   mp,
	}

	dtos, problems := handlerDTOs(hp)

	// 根类型 = 各 DTO 本身
	roots := make([]string, 0, len(dtos))
	extra := map[string]*ast.StructType{}
	for _, ref := range dtos {
		roots = append(roots, ref.compKey)
		if ref.inlineStruct != nil {
			extra[ref.compKey] = ref.inlineStruct
		}
	}
	// 走类型图,把嵌套类型也捞进来(它们的字段说明在 service/model 包里)
	typeStructs := walkTypes(pkgs, roots, extra, hp)

	docs := map[string]map[string]string{}
	for key, st := range typeStructs {
		if d := structDocs(st); len(d) > 0 {
			docs[key] = d
		}
	}

	return &result{dtos: dtos, docs: docs, skipped: problems}, nil
}

// render 生成 Go 源码
func render(res *result) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gen-swagger-schema. DO NOT EDIT.\n")
	buf.WriteString("//\n")
	buf.WriteString("// 改 handler 或 DTO 之后重跑:go run ./cmd/gen-swagger-schema\n")
	buf.WriteString("// 漂移由 main_test.go 盯着(重跑生成器跟仓库里这份逐字比)。\n")
	buf.WriteString("//\n")
	buf.WriteString("// RequestDTOs:路由 handler 方法 → 请求体 DTO 类型。\n")
	buf.WriteString("//\n")
	buf.WriteString("// key 形如 \"(*UserHandler).Create\",与运行期 hertz 路由表里的\n")
	buf.WriteString("// utils.NameOfFunction(handlerFunc) 逐字对齐(去掉包路径前缀与 -fm 后缀)。\n")
	buf.WriteString("// 对不上 ⇒ schema 挂不到那条路由上,而且不报错 —— 所以要对齐。\n")
	buf.WriteString("package v1\n\n")

	// 需要的 import:生成物里出现的所有外部限定名(照抄源码里的 import 路径)
	imports := map[string]string{}
	for _, ref := range res.dtos {
		if !ref.local {
			imports[ref.qualifier] = ref.importPath
		}
		// 匿名 struct 的字段里可能还引用别的包(如 jsonid.IDList)
		for q, p := range ref.extraImports {
			imports[q] = p
		}
	}
	if len(imports) > 0 {
		names := make([]string, 0, len(imports))
		for q := range imports {
			names = append(names, q)
		}
		sort.Strings(names)
		buf.WriteString("import (\n")
		for _, q := range names {
			fmt.Fprintf(&buf, "\t%q\n", imports[q])
		}
		buf.WriteString(")\n\n")
	}

	keys := make([]string, 0, len(res.dtos))
	for k := range res.dtos {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	// 源码里就地写的匿名 struct:在生成文件里声明成具名类型再引用
	inlineDecls := make([]string, 0)
	for _, k := range keys {
		ref := res.dtos[k]
		if ref.inlineDecl == "" {
			continue
		}
		inlineDecls = append(inlineDecls, ref.inlineDecl)
	}
	if len(inlineDecls) > 0 {
		sort.Strings(inlineDecls)
		buf.WriteString("// 源码里就地写的匿名 struct —— 生成文件里声明成具名类型再引用。\n")
		for _, d := range inlineDecls {
			buf.WriteString(d)
			buf.WriteString("\n\n")
		}
	}

	buf.WriteString("// RequestDTOs 路由 handler 方法 → 请求体 DTO 类型。\n")
	buf.WriteString("//\n")
	buf.WriteString("// 空值 = 那条路由没有 JSON 请求体(GET / DELETE / 文件上传等)。\n")
	buf.WriteString("var RequestDTOs = map[string]any{\n")
	for _, k := range keys {
		fmt.Fprintf(&buf, "\t%q: %s,\n", k, res.dtos[k].expr)
	}
	buf.WriteString("}\n\n")

	buf.WriteString("// RequestFieldDocs 组件名 → (json 字段名 → 字段说明)。\n")
	buf.WriteString("//\n")
	buf.WriteString("// 说明取自结构体字段的行尾注释 —— 本仓 DTO 的字段语义就写在那一行,\n")
	buf.WriteString("// 没有集中的字段字典。不搬进 Swagger UI,字段契约就还是半张。\n")
	buf.WriteString("var RequestFieldDocs = map[string]map[string]string{\n")
	docKeys := make([]string, 0, len(res.docs))
	for k := range res.docs {
		docKeys = append(docKeys, k)
	}
	sort.Strings(docKeys)
	for _, k := range docKeys {
		fmt.Fprintf(&buf, "\t%q: {\n", k)
		fieldKeys := make([]string, 0, len(res.docs[k]))
		for f := range res.docs[k] {
			fieldKeys = append(fieldKeys, f)
		}
		sort.Strings(fieldKeys)
		for _, f := range fieldKeys {
			fmt.Fprintf(&buf, "\t\t%q: %q,\n", f, res.docs[k][f])
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	if len(res.skipped) > 0 {
		buf.WriteString("\n// 下面这些 handler 没能确定请求体 DTO(生成时跳过,详见 cmd/gen-swagger-schema):\n")
		for _, s := range res.skipped {
			fmt.Fprintf(&buf, "//   - %s\n", oneLine(s))
		}
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt 失败(源码 %s): %w", buf.String(), err)
	}
	return out, nil
}

// findModuleRoot 往上找 go.mod 所在目录
//
// 生成器既可能被 `go run ./cmd/gen-swagger-schema`(cwd = server/)跑,
// 也可能被包内测试(cwd = server/cmd/gen-swagger-schema/)跑 ——
// 两种 cwd 差两级,所以不能写死相对路径。
func findModuleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("往上找不到 go.mod")
		}
		dir = parent
	}
}
